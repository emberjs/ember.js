/**
 * Compiles the standard library routines ahead of time and writes them as
 * data to packages/@glimmer/opcode-compiler/lib/opcode-builder/stdlib-data.ts.
 *
 * Run it after changing an opcode handler, an opcode number, or a routine in
 * packages/@glimmer/opcode-compiler/lib/opcode-builder/helpers/stdlib.ts.
 * A test checks that the committed file matches a fresh build.
 */
import '@swc-node/register/esm-register';
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'packages/@glimmer/opcode-compiler/lib/opcode-builder/stdlib-data.ts');

const record = await import('../packages/@glimmer/opcode-compiler/lib/aot/record.ts');
const { handlerFor } = await import('../packages/@glimmer/opcode-compiler/lib/aot/handlers.ts');
const source =
  await import('../packages/@glimmer/opcode-compiler/lib/opcode-builder/helpers/stdlib.ts');

const ROUTINES = [
  ['MAIN', source.MAIN],
  ['TRUSTING_NON_DYNAMIC_APPEND', source.TRUSTING_NON_DYNAMIC_APPEND],
  ['CAUTIOUS_NON_DYNAMIC_APPEND', source.CAUTIOUS_NON_DYNAMIC_APPEND],
  ['TRUSTING_APPEND', source.TRUSTING_APPEND],
  ['CAUTIOUS_APPEND', source.CAUTIOUS_APPEND],
];

const exportByName = new Map(ROUTINES.map(([exportName, routine]) => [routine.name, exportName]));
const imports = new Map();

function importHandler(type) {
  let { module, name } = handlerFor(type);
  if (!imports.has(module)) imports.set(module, new Set());
  imports.get(module).add(name);
  return name;
}

let body = '';

for (const [exportName, routine] of ROUTINES) {
  const constants = new record.RecordingConstants();
  const programs = [];
  const index = record.recordProgram((op) => routine.build(op, null), 0, {
    meta: source.STDLIB_META,
    constants,
    programs,
  });

  if (programs.length !== 1 || constants.entries.length !== 0) {
    throw new Error(`stdlib routine ${routine.name} must not use constants or nested blocks`);
  }

  const program = programs[index];
  const handlers = record.syscallsIn(program.words).map(importHandler);
  const fixups = program.stdlibRefs.map(([at, name]) => {
    const target = exportByName.get(name);
    if (!target)
      throw new Error(`stdlib routine ${routine.name} references unknown routine ${name}`);
    return `[${at}, () => ${target}]`;
  });

  body += `export const ${exportName}: StdlibRoutine = {
  name: ${JSON.stringify(routine.name)},
  size: ${program.size},
  words: [${program.words.join(', ')}],
  handlers: [${handlers.join(', ')}],
  fixups: [${fixups.join(', ')}],
};

`;
}

function header() {
  let text = `/* This file is generated by bin/build-aot-stdlib.mjs. Do not edit. */
import type { StdlibRoutine } from '@glimmer/interfaces';
import type { AotBlock } from '../aot/template';
`;

  for (const [module, names] of [...imports.entries()].sort()) {
    text += `import { ${[...names].sort().join(', ')} } from '${module}';\n`;
  }

  return text;
}

writeFileSync(out, `${header()}\n${body}`);

// The default template is a statement, and the statement compiler imports
// the routines written above, so it loads after that write.
const { YieldOp } = await import('../packages/@glimmer/opcode-compiler/lib/syntax/statements.ts');
const { printBlock } = await import('../packages/@glimmer/opcode-compiler/lib/aot/print.ts');
const { WrappedComponent, ATTRS_BLOCK } =
  await import('../packages/@glimmer/opcode-compiler/lib/opcode-builder/helpers/components.ts');
const { meta } =
  await import('../packages/@glimmer/opcode-compiler/lib/opcode-builder/helpers/shared.ts');

const bind = (local, module, name) => {
  if (module === STDLIB_MODULE) return name;
  if (!imports.has(module)) imports.set(module, new Set());
  imports.get(module).add(name);
  return name;
};
const STDLIB_MODULE = '@glimmer/opcode-compiler/lib/opcode-builder/stdlib-data';
const layout = {
  id: '1b32f5c2-7623-43d6-a0ad-9672898920a1',
  block: [[[YieldOp, 1, null]], ['&default'], []],
  moduleName: '__default__.hbs',
  owner: null,
  scope: null,
  isStrictMode: true,
};

{
  const constants = new record.RecordingConstants();
  const programs = [];
  record.recordStatements(layout.block[0], 1, { meta: meta(layout), constants, programs });
  body += `export const DEFAULT_TEMPLATE: AotBlock = ${printBlock(['&default'], constants.entries, programs, bind)};

`;
}

{
  // Classic components without a template render the default template as a
  // wrapped layout, the way WrappedBuilder compiles one in the browser.
  const constants = new record.RecordingConstants();
  const programs = [];
  const symbols = ['&default', ATTRS_BLOCK];
  record.recordProgram((op) => WrappedComponent(op, layout, symbols.length), 1, {
    meta: meta(layout),
    constants,
    programs,
  });
  body += `export const DEFAULT_TEMPLATE_WRAPPED: AotBlock = ${printBlock(symbols, constants.entries, programs, bind)};
`;
}

writeFileSync(out, `${header()}\n${body}`);
execSync(`pnpm exec prettier --write --log-level warn ${JSON.stringify(out)}`, {
  cwd: root,
  stdio: 'inherit',
});
process.stdout.write(`wrote ${out}\n`);
